function stripArabicDiacriticsSimple(input: string): string {
  return (input || '')
    .replace(/[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .trim();
}

export function filterHisnAdhkar(
  items: HisnDhikrItem[],
  selectedOccasion: 'all' | 'favorites' | HisnOccasionId,
  searchQuery: string,
  favoriteIds: string[]
): HisnDhikrItem[] {
  const favSet = new Set(favoriteIds);
  const cleanQuery = stripArabicDiacriticsSimple(searchQuery).toLowerCase();

  return items.filter((item) => {
    if (selectedOccasion === 'favorites' && !favSet.has(item.id)) {
      return false;
    }
    if (
      selectedOccasion !== 'all' &&
      selectedOccasion !== 'favorites' &&
      item.occasionId !== selectedOccasion
    ) {
      return false;
    }
    if (!cleanQuery) return true;
    const haystack = stripArabicDiacriticsSimple(
      `${item.titleArabic} ${item.occasionArabic} ${item.text} ${item.reward}`
    ).toLowerCase();
    return haystack.includes(cleanQuery);
  });
}
